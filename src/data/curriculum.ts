import type { Lesson, Subject } from "../types/learning";

type TopicSeed = {
  id: string;
  title: string;
  introduction: string;
  keyIdeas: string[];
  example: string;
  check: string;
  wrong: string[];
};

function makeLessons(topics: TopicSeed[]): Lesson[] {
  return topics.map((topic) => ({
    id: topic.id,
    title: topic.title,
    duration: "6 min",
    introduction: topic.introduction,
    keyIdeas: topic.keyIdeas,
    example: topic.example,
    question: {
      prompt: topic.check,
      options: [topic.keyIdeas[0], ...topic.wrong.slice(0, 3)],
      correctAnswer: 0,
      explanation: topic.keyIdeas[0],
    },
  }));
}

